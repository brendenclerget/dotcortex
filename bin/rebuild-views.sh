#!/usr/bin/env bash
# Layer resolution + tool-view rebuild. The single engine that init, update,
# sync, and context commands all call.
#
# Resolves .dotcortex/layers/{org,team}/<category>/ into .dotcortex/<category>/
# as per-file relative symlinks (team wins on same-name collision; every
# override is reported, never silent), then ensures the tool views
# (.claude/<cat>, .agents/skills) point at the resolved directories.
#
# Safety: a resolved directory is only ever rebuilt if it carries the
# .rebuilt-by-dotcortex marker (or is absent/empty). A directory with real
# user files and no marker aborts with instructions — this script never
# deletes content it did not generate.
#
# Usage: bin/rebuild-views.sh [--root <project-root>]
set -euo pipefail

ROOT="$(pwd)"
while [ "$#" -gt 0 ]; do
  case "$1" in
    --root) ROOT="${2:?}"; shift ;;
    *) echo "rebuild-views.sh: unknown argument: $1" >&2; exit 2 ;;
  esac
  shift
done

DC="$ROOT/.dotcortex"
LAYERS="$DC/layers"
MARKER=".rebuilt-by-dotcortex"
CATEGORIES="commands skills knowledge templates memory"

[ -d "$DC" ] || { echo "rebuild-views.sh: $DC not found" >&2; exit 2; }

resolve_category() {
  local cat="$1"
  local resolved="$DC/$cat"

  # No layer provides this category and no resolved dir exists: nothing to do.
  if [ ! -d "$LAYERS/org/$cat" ] && [ ! -d "$LAYERS/team/$cat" ]; then
    return 0
  fi

  # Safety gate before deleting anything. A resolved path may be replaced only
  # if it is (a) absent, (b) an empty dir, or (c) a marked dir containing
  # NOTHING but the marker, generated symlinks, and directories. Any regular
  # file — even inside a marked tree (a user may have saved work into the
  # resolved view by mistake) — aborts with the offenders listed.
  if [ -e "$resolved" ] || [ -L "$resolved" ]; then
    if [ ! -d "$resolved" ] || [ -L "$resolved" ]; then
      echo "rebuild-views.sh: ABORT — $resolved exists but is not a regular directory." >&2
      exit 1
    fi
    if [ -n "$(ls -A "$resolved" 2>/dev/null)" ] && [ ! -f "$resolved/$MARKER" ]; then
      echo "rebuild-views.sh: ABORT — $resolved contains files not generated by this script." >&2
      echo "  Move authored content into $LAYERS/team/$cat/ (or org), then re-run." >&2
      exit 1
    fi
    local offenders
    offenders="$(find "$resolved" -type f ! -name "$MARKER" 2>/dev/null || true)"
    if [ -n "$offenders" ]; then
      echo "rebuild-views.sh: ABORT — regular files found inside generated dir $resolved:" >&2
      echo "$offenders" | sed 's/^/    /' >&2
      echo "  These were not created by this script. Move them into $LAYERS/team/$cat/ (or org), then re-run." >&2
      exit 1
    fi
  fi
  rm -rf "$resolved"
  mkdir -p "$resolved"
  touch "$resolved/$MARKER"

  # org first, team second: team's link replaces org's on the same relpath.
  local layer rel link_dir
  for layer in org team; do
    [ -d "$LAYERS/$layer/$cat" ] || continue
    while IFS= read -r file; do
      rel="${file#"$LAYERS/$layer/$cat/"}"
      link_dir="$resolved/$(dirname "$rel")"
      mkdir -p "$link_dir"
      if [ -e "$resolved/$rel" ] || [ -L "$resolved/$rel" ]; then
        echo "OVERRIDE (team wins over org): $cat/$rel"
        rm -f "$resolved/$rel"
      fi
      ln -s "$(python3 -c 'import os,sys; print(os.path.relpath(sys.argv[1], sys.argv[2]))' "$file" "$link_dir")" \
        "$resolved/$rel"
    done < <(find "$LAYERS/$layer/$cat" -type f ! -name "$MARKER" | sort)
  done
}

# Same rule as the installer: a symlink pointing at the expected resolved dir
# stays; a dangling one is repaired; one pointing anywhere else aborts untouched.
ensure_view_link() {
  local view="$1" target="$2" expected_dir="$3"
  if [ -L "$view" ]; then
    local expected actual state
    expected="$(cd "$expected_dir" && pwd -P)"
    # Distinguish a truly missing target (ENOENT -> repairable) from one we
    # merely cannot see (EACCES, ELOOP, ... -> unexpected, abort untouched).
    state="$(python3 -c '
import os, sys
try:
    os.stat(sys.argv[1]); print("exists")
except FileNotFoundError:
    print("missing")
except OSError:
    print("unknown")' "$view")"
    if [ "$state" = "missing" ]; then
      # Truly dangling (target does not exist at all): safe to repair.
      echo "rebuild-views.sh: repairing dangling view symlink: $view"
      rm -f "$view"
    elif [ "$state" = "unknown" ]; then
      echo "rebuild-views.sh: ABORT — cannot verify target of symlink $view (permission/loop):" >&2
      echo "  $(readlink "$view")" >&2
      echo "  Refusing to modify it. Fix or remove the symlink, then re-run." >&2
      exit 1
    else
      # Target exists. Only an accessible DIRECTORY resolving to the expected
      # path is acceptable; a file target or inaccessible dir is "unexpected",
      # never "dangling" — abort untouched.
      actual=""
      if [ -d "$view" ]; then
        actual="$(cd "$view" 2>/dev/null && pwd -P || true)"
      fi
      if [ "$actual" = "$expected" ]; then
        return 0
      fi
      echo "rebuild-views.sh: ABORT — $view is a symlink to an unexpected target:" >&2
      echo "  $(readlink "$view") (expected to resolve to $expected)" >&2
      echo "  Refusing to modify it. Fix or remove the symlink, then re-run." >&2
      exit 1
    fi
  elif [ -d "$view" ]; then
    # A real directory. The ONLY real dir we may replace is the installer's
    # pre-init bootstrap view: entries are exactly a subset of the two known
    # bootstrap filenames, each a symlink resolving into .dotcortex. Any other
    # name, any regular file, any foreign symlink = user content: leave it.
    local entry unmanaged=0 dc_real base
    dc_real="$(python3 -c 'import os,sys; print(os.path.realpath(sys.argv[1]))' "$DC")"
    for entry in "$view"/* "$view"/.[!.]*; do
      [ -e "$entry" ] || [ -L "$entry" ] || continue
      base="$(basename "$entry")"
      case "$base" in cortex-init.md|cortex-update.md) ;; *) unmanaged=1; break ;; esac
      if [ ! -L "$entry" ]; then unmanaged=1; break; fi
      case "$(python3 -c 'import os,sys; print(os.path.realpath(sys.argv[1]))' "$entry")" in
        "$dc_real"/*) ;;
        *) unmanaged=1; break ;;
      esac
    done
    if [ "$unmanaged" -eq 1 ]; then
      echo "rebuild-views.sh: WARN — $view is a real directory with unmanaged content; leaving it untouched." >&2
      return 0
    fi
    echo "rebuild-views.sh: replacing managed bootstrap view dir: $view"
    rm -rf "$view"
  elif [ -e "$view" ]; then
    echo "rebuild-views.sh: WARN — $view exists and is not a symlink; leaving it untouched." >&2
    return 0
  fi
  mkdir -p "$(dirname "$view")"
  ln -s "$target" "$view"
}

for cat in $CATEGORIES; do
  resolve_category "$cat"
done

# Tool views point at resolved dirs (only for categories that resolved).
for cat in commands skills knowledge memory; do
  [ -d "$DC/$cat" ] && ensure_view_link "$ROOT/.claude/$cat" "../.dotcortex/$cat" "$DC/$cat"
done
[ -d "$DC/skills" ] && ensure_view_link "$ROOT/.agents/skills" "../.dotcortex/skills" "$DC/skills"

echo "rebuild-views.sh: done ($ROOT)"
