#!/usr/bin/env bash
# Layer resolution + tool-view rebuild. The single engine that init, update,
# sync, and context commands all call.
#
# Resolves .dotcortex/layers/{org,team}/<category>/ into .dotcortex/<category>/
# as per-file relative symlinks (team wins on same-name collision; every
# override is reported, never silent), then ensures the tool views
# (.claude/<cat>, .agents/skills) point at the resolved directories.
#
# Safety: a resolved directory is only ever rebuilt if it carries the
# .rebuilt-by-dotcortex marker (or is absent/empty). A directory with real
# user files and no marker aborts with instructions — this script never
# deletes content it did not generate.
#
# Usage: bin/rebuild-views.sh [--root <project-root>]
set -euo pipefail

ROOT="$(pwd)"
while [ "$#" -gt 0 ]; do
  case "$1" in
    --root) ROOT="${2:?}"; shift ;;
    *) echo "rebuild-views.sh: unknown argument: $1" >&2; exit 2 ;;
  esac
  shift
done

DC="$ROOT/.dotcortex"
LAYERS="$DC/layers"
MARKER=".rebuilt-by-dotcortex"
CATEGORIES="commands skills knowledge templates memory"

[ -d "$DC" ] || { echo "rebuild-views.sh: $DC not found" >&2; exit 2; }

resolve_category() {
  local cat="$1"
  local resolved="$DC/$cat"

  # No layer provides this category and no resolved dir exists: nothing to do.
  if [ ! -d "$LAYERS/org/$cat" ] && [ ! -d "$LAYERS/team/$cat" ]; then
    return 0
  fi

  # Safety gate before deleting anything. A resolved path may be replaced only
  # if it is (a) absent, (b) an empty dir, or (c) a marked dir containing
  # NOTHING but the marker, generated symlinks, and directories. Any regular
  # file — even inside a marked tree (a user may have saved work into the
  # resolved view by mistake) — aborts with the offenders listed.
  if [ -e "$resolved" ] || [ -L "$resolved" ]; then
    if [ ! -d "$resolved" ] || [ -L "$resolved" ]; then
      echo "rebuild-views.sh: ABORT — $resolved exists but is not a regular directory." >&2
      exit 1
    fi
    if [ -n "$(ls -A "$resolved" 2>/dev/null)" ] && [ ! -f "$resolved/$MARKER" ]; then
      echo "rebuild-views.sh: ABORT — $resolved contains files not generated by this script." >&2
      echo "  Move authored content into $LAYERS/team/$cat/ (or org), then re-run." >&2
      exit 1
    fi
    local offenders
    offenders="$(find "$resolved" -type f ! -name "$MARKER" 2>/dev/null || true)"
    if [ -n "$offenders" ]; then
      echo "rebuild-views.sh: ABORT — regular files found inside generated dir $resolved:" >&2
      echo "$offenders" | sed 's/^/    /' >&2
      echo "  These were not created by this script. Move them into $LAYERS/team/$cat/ (or org), then re-run." >&2
      exit 1
    fi
  fi
  rm -rf "$resolved"
  mkdir -p "$resolved"
  touch "$resolved/$MARKER"

  # org first, team second: team's link replaces org's on the same relpath.
  local layer rel link_dir
  for layer in org team; do
    [ -d "$LAYERS/$layer/$cat" ] || continue
    while IFS= read -r file; do
      rel="${file#"$LAYERS/$layer/$cat/"}"
      link_dir="$resolved/$(dirname "$rel")"
      mkdir -p "$link_dir"
      if [ -e "$resolved/$rel" ] || [ -L "$resolved/$rel" ]; then
        echo "OVERRIDE (team wins over org): $cat/$rel"
        rm -f "$resolved/$rel"
      fi
      ln -s "$(python3 -c 'import os,sys; print(os.path.relpath(sys.argv[1], sys.argv[2]))' "$file" "$link_dir")" \
        "$resolved/$rel"
    done < <(find "$LAYERS/$layer/$cat" -type f ! -name "$MARKER" | sort)
  done
}

ensure_view_link() {
  local view="$1" target="$2"
  if [ -L "$view" ]; then
    rm -f "$view"
  elif [ -e "$view" ]; then
    echo "rebuild-views.sh: WARN — $view exists and is not a symlink; leaving it untouched." >&2
    return 0
  fi
  mkdir -p "$(dirname "$view")"
  ln -s "$target" "$view"
}

for cat in $CATEGORIES; do
  resolve_category "$cat"
done

# Tool views point at resolved dirs (only for categories that resolved).
for cat in commands skills knowledge memory; do
  [ -d "$DC/$cat" ] && ensure_view_link "$ROOT/.claude/$cat" "../.dotcortex/$cat"
done
[ -d "$DC/skills" ] && ensure_view_link "$ROOT/.agents/skills" "../.dotcortex/skills"

echo "rebuild-views.sh: done ($ROOT)"
